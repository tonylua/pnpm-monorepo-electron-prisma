const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const { DatabaseSync } = require('node:sqlite')

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vfs-share-'))
const dll = path.resolve(__dirname, '../../apps/desktop/resources/encrypted_vfs.dll')
const boot = new DatabaseSync(':memory:', { allowExtension: true })
boot.loadExtension(dll)
const file = path.join(dir, 't.db')
const key = crypto.randomBytes(32)
boot.prepare('SELECT encrypted_vfs_register_db(?, ?, ?)').get(file, key, 'create-new')
const a = new DatabaseSync(file)
a.exec('CREATE TABLE t(note TEXT)')
const b = new DatabaseSync(file)
b.exec("INSERT INTO t(note) VALUES ('from-b')")
a.exec("INSERT INTO t(note) VALUES ('from-a')")
const rows = a.prepare('SELECT note FROM t ORDER BY rowid').all()
a.close()
b.close()
const c = new DatabaseSync(file)
const again = c.prepare('SELECT note FROM t ORDER BY rowid').all()
c.close()
boot.close()
process.stdout.write(`${JSON.stringify({ rows, again, header: fs.readFileSync(file).subarray(0, 5).toString() })}\n`)
fs.rmSync(dir, { recursive: true, force: true })
